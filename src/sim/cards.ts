export const BLACK_CARDS: ReadonlyArray<BlackCard> = RAW_BLACK_CARDS.map((item, idx) => ({
  id: idx + 1,
  code: `B-${String(idx + 1).padStart(3, "0")}`,
  pack: item.pack,
  text: item.text,
  pick: item.pick ?? 1
}))

export const WHITE_CARDS: ReadonlyArray<WhiteCard> = RAW_WHITE_CARDS.map((item, idx) => ({
  id: 1001 + idx,
  code: `W-${String(idx + 1).padStart(3, "0")}`,
  pack: item.pack,
  text: item.text,
  tags: item.tags
}))

const BLACK_MAP = new Map<number, BlackCard>(BLACK_CARDS.map((card) => [card.id, card]))
const WHITE_MAP = new Map<number, WhiteCard>(WHITE_CARDS.map((card) => [card.id, card]))

export const WRITE_IN_CARD_BASE_ID = 900000

export function getBlackCard(id: number): BlackCard {
  return BLACK_MAP.get(id) ?? BLACK_CARDS[0]!
}

export function getWhiteCard(id: number, customTexts?: Readonly<Record<number, string>>): WhiteCard {
  const builtin = WHITE_MAP.get(id)
  if (builtin !== undefined) return builtin
  const text = customTexts?.[id]
  if (text !== undefined) {
    return {
      id,
      code: id >= WRITE_IN_CARD_BASE_ID ? "W-INK" : `W-C${id}`,
      pack: "core",
      text,
      tags: ["absurd", "social"]
    }
  }
  return WHITE_CARDS[0]!
}

export function getDeckIdsForPacks(packs: ReadonlyArray<CardPackId>): {
  readonly blackIds: ReadonlyArray<number>
  readonly whiteIds: ReadonlyArray<number>
} {
  const active = packs.length > 0 ? packs : ALL_PACK_IDS
  const blackIds = BLACK_CARDS.filter((c) => active.includes(c.pack)).map((c) => c.id)
  const whiteIds = WHITE_CARDS.filter((c) => active.includes(c.pack)).map((c) => c.id)
  return {
    blackIds: blackIds.length > 0 ? blackIds : BLACK_CARDS.map((c) => c.id),
    whiteIds: whiteIds.length > 0 ? whiteIds : WHITE_CARDS.map((c) => c.id)
  }
}

export interface SentenceSegment {
  readonly text: string
  readonly isFill: boolean
}

function trimTrailingPeriod(text: string): string {
  return text.endsWith(".") ? text.slice(0, -1) : text
}

/**
 * Combines a Black Prompt card and 1–2 White Response card texts into structured segments
 * so the HUD and PNG exporter can display the complete punchline with highlighted fills!
 */
export function buildCompletedSentence(
  promptText: string,
  answerTexts: ReadonlyArray<string>
): ReadonlyArray<SentenceSegment> {
  const blankRegex = /_{3,}/g
  const blanks = promptText.match(blankRegex)
  if (blanks === null || blanks.length === 0) {
    const out: Array<SentenceSegment> = [{ text: promptText, isFill: false }]
    if (answerTexts.length > 0) {
      out.push({ text: "  —  ", isFill: false })
      answerTexts.forEach((ans, idx) => {
        if (idx > 0) out.push({ text: " / ", isFill: false })
        out.push({ text: ans, isFill: true })
      })
    }
    return out
  }

  const parts = promptText.split(blankRegex)
  const segments: Array<SentenceSegment> = []
  for (let i = 0; i < parts.length; i++) {
    const piece = parts[i]!
    if (piece.length > 0) {
      segments.push({ text: piece, isFill: false })
    }
    if (i < parts.length - 1) {
      const answer = answerTexts[i]
      if (answer !== undefined) {
        const nextStartsLowerOrPunct = parts[i + 1] !== undefined && /^[.,!?;:'")]/.test(parts[i + 1]!)
        const cleaned = nextStartsLowerOrPunct ? trimTrailingPeriod(answer) : answer
        segments.push({ text: cleaned, isFill: true })
      } else {
        segments.push({ text: "______", isFill: false })
      }
    }
  }
  return segments
}

export function formatCompletedSentencePlain(
  promptText: string,
  answerTexts: ReadonlyArray<string>
): string {
  return buildCompletedSentence(promptText, answerTexts)
    .map((seg) => seg.text)
    .join("")
}
